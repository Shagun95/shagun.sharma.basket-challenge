public enum GameEvent
{
    /// <summary>
    /// Used when the ball is launched though input
    /// </summary>
    LAUNCH_BALL,
    /// <summary>
    /// Used to add a score to the player
    /// </summary>
    PLAYER_SCORED,
    /// <summary>
    /// Player moved to new position
    /// </summary>
    POSITION_CHANGED,
    /// <summary>
    /// Game has started
    /// </summary>
    GAME_STARTED,
    /// <summary>
    /// Game is finished
    /// </summary>
    GAME_FINISHED
}
